import {readFile, mkdir, writeFile} from 'node:fs/promises';
import {createHash} from 'node:crypto';

export const LEGACY_SHA256 = 'e34303574abc69b64666621d74edce0cef9dc2687641bd5ff22ae517f10a3950';
const root = new URL('../', import.meta.url);
const source = await readFile(new URL('src/legacy-v4.1.mjs', root), 'utf8');
if (createHash('sha256').update(source).digest('hex') !== LEGACY_SHA256)
  throw Error('Protected legacy source changed; wrapper generation refused.');
if (source.split('export default {').length !== 2 || /\bimport\s/.test(source))
  throw Error('Legacy module shape changed; review the generator.');
const generated = '// Generated by scripts/generate-legacy-visual.mjs. Do not edit.\n' +
  `// Protected source SHA-256: ${LEGACY_SHA256}\n` +
  'export function createLegacyVisual(fetch) {\n' + source.replace('export default {', 'return {') + '\n}\n';
const target = new URL('src/generated/legacy-visual.mjs', root);
if (process.argv.includes('--check')) {
  if (await readFile(target, 'utf8') !== generated) throw Error('Generated legacy wrapper is stale.');
} else {
  await mkdir(new URL('src/generated/', root), {recursive: true});
  await writeFile(target, generated);
}
